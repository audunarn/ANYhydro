def validate_actual_controls(args: argparse.Namespace) -> dict:
    """Fixed actual-case diagnostic scope gate (CLI level).

    The CLI accepts exactly the registered actual controls: the original
    expected case hash, retained DOFs 0/2/6/8, angular counts 64/128/256
    and the 1536 MiB virtual cap. Anything changed, duplicated, reordered
    or subset is refused before any output directory is created, and a
    command-line --expected-case-hash override never broadens actual-case
    authority. Small synthetic tests substitute test-only module defaults
    or call the internal run/assembly entry points directly; the actual
    CLI gates are not relaxed for them.
    """
    expected = str(args.expected_case_hash)
    if expected != str(ACTUAL_CASE_HASH):
        raise CandidateRefusal(f'expected case hash {expected!r} is not the '
                              'registered actual case hash; the command-line '
                              'override does not broaden actual-case authority')
    retained = tuple(int(d) for d in args.retained_dofs)
    if retained != tuple(int(d) for d in ACTUAL_RETAINED_DOFS):
        raise CandidateRefusal(f'retained DOFs {list(retained)} are not the '
                               f'registered actual controls '
                               f'{[int(d) for d in ACTUAL_RETAINED_DOFS]}; '
                               'changed, duplicated, reordered or subset '
                               'controls are refused')
    angular = tuple(int(c) for c in args.angular_counts)
    if angular != tuple(int(c) for c in ACTUAL_ANGULAR_COUNTS):
        raise CandidateRefusal(f'angular counts {list(angular)} are not the '
                               f'registered actual controls '
                               f'{[int(c) for c in ACTUAL_ANGULAR_COUNTS]}; '
                               'changed, duplicated, reordered or subset '
                               'controls are refused')
    rlimit = int(args.rlimit_mib)
    if rlimit != int(ACTUAL_RLIMIT_MIB):
        raise CandidateRefusal(f'virtual cap {rlimit} MiB is not the registered '
                               f'actual control {int(ACTUAL_RLIMIT_MIB)} MiB')
    return {'expected_case_hash': expected,
            'retained_dofs': [int(d) for d in retained],
            'angular_counts': [int(c) for c in angular],
            'rlimit_mib': rlimit,
            'registered_frozen_rate': [float(v) for v in REGISTERED_FROZEN_RATE]}


def parse_args(argv) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description='Experimental retained-field physical-hull potential-tested '
                    'Neumann candidate for one frozen development case.')
    parser.add_argument('--case', required=True, help='frozen case directory')
    parser.add_argument('--parent', required=True,
                        help='parent results directory holding summary.json')
    parser.add_argument('--output', required=True,
                        help='fresh output directory outside the immutable trees')
    parser.add_argument('--expected-case-hash', default=DEFAULT_CASE_HASH,
                        help='required case_hash of the frozen case')
    parser.add_argument('--retained-dofs', type=int, nargs='+',
                        default=list(DEFAULT_RETAINED_DOFS),
                        help='retained DOF indices for reporting')
    parser.add_argument('--angular-counts', type=int, nargs='+',
                        default=list(DEFAULT_ANGULAR_COUNTS),
                        help='fixed angular counts for the far power')
    parser.add_argument('--rlimit-mib', type=int, default=DEFAULT_RLIMIT_MIB,
                        help='RLIMIT_AS virtual address-space cap (Linux)')
    return parser.parse_args(argv)


def run(args: argparse.Namespace, ownership: dict | None = None) -> dict:
    started = time.perf_counter()
    rlimit = apply_virtual_limit(args.rlimit_mib)
    if platform.system() == 'Linux' and not rlimit['applied']:
        raise CandidateRefusal('required Linux virtual address-space cap unavailable')
    try:
        case_dir, output_dir = resolve_and_guard_output(Path(args.case), Path(args.output))
    except ValueError as exc:
        raise CandidateRefusal(str(exc)) from exc
    if output_dir.exists():
        raise CandidateRefusal(f'output directory {output_dir} already exists; '
                               'only a fresh directory is accepted')
    if not case_dir.is_dir():
        raise CandidateRefusal(f'case directory {case_dir} does not exist')
    parent_dir = Path(args.parent).resolve()
    if not parent_dir.is_dir():
        raise CandidateRefusal(f'parent directory {parent_dir} does not exist')
    output_dir.mkdir(parents=True)
    # from here on this run owns the fresh resolved output directory it just
    # created; failure records may be written only there
    if ownership is not None:
        ownership['owned_output'] = output_dir
    write_status(output_dir, 'starting', case_dir=str(case_dir),
                 output_directory=str(output_dir), solve_attempts_this_run=0)

    threadpool = verify_single_thread_runtime(posix=platform.system() != 'Windows')
    write_status(output_dir, 'runtime_measured', threadpool=threadpool)

    case = load_candidate_case(case_dir, args.expected_case_hash)
    retained = tuple(int(d) for d in args.retained_dofs)
    if not retained or len(set(retained)) != len(retained) \
            or any(d < 0 or d >= case['ndof'] for d in retained):
        raise CandidateRefusal(f'retained DOF indices {retained} invalid for '
                               f'{case["ndof"]} stored DOFs')
    angular_counts = tuple(int(c) for c in args.angular_counts)
    if not angular_counts or any(c < 16 or c > 4096 for c in angular_counts):
        raise CandidateRefusal('angular counts must be integers in [16,4096]')
    frozen = load_frozen_rate(parent_dir, case)
    summary_path = parent_dir / 'summary.json'
    summary_hash_pre = sha256_file(summary_path)

    input_files = ['input.npz', 'radiation.npz', 'case.json', 'status.json'] \
        + [f'operator-{q}.npz' for q in range(case['nq'])]
    pre_hashes = {}
    for name in input_files:
        path = case_dir / name
        if not path.is_file():
            raise CandidateRefusal(f'missing required case file: {path}')
        pre_hashes[name] = sha256_file(path)
    write_status(output_dir, 'validated', case_hash=case['case_json'].get('case_hash'),
                 solve_attempts_this_run=0)

    # per-actual-run numerical solve count, saved before the solve
    write_status(output_dir, 'pre_solve', case_hash=case['case_json'].get('case_hash'),
                 solve_attempts_this_run=1, solve_recorded_before_solve=True,
                 note='single retained-case linear solve of this run; shared '
                      'two-solve cap is enforced outside this process')
    assembly_started = time.perf_counter()
    A, b = assemble_candidate_system(case_dir, case)
    operator_files = {f'operator-{q}.npz': pre_hashes[f'operator-{q}.npz']
                     for q in range(case['nq'])}
    sigma, solve_meta = solve_equilibrated(A, b)
    solve_meta['assembly_plus_solve_seconds'] = time.perf_counter() - assembly_started
    write_status(output_dir, 'solved', solve_attempts_this_run=1)

    fields = recover_fields(case_dir, case, sigma, frozen['rho'], frozen['omega'])
    fields['sigma'] = sigma
    post_hashes = {name: sha256_file(case_dir / name) for name in input_files}
    summary_hash_post = sha256_file(summary_path)
    if post_hashes != pre_hashes:
        raise CandidateRefusal('stored case files changed during the run; '
                               'inputs must never be modified')
    if summary_hash_post != summary_hash_pre:
        raise CandidateRefusal('parent summary.json changed during the run; '
                               'inputs must never be modified')

    runtime = {
        'rlimit': rlimit,
        'threadpool': threadpool,
        'thread_env': {name: os.environ.get(name) for name in
                      ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS',
                       'NUMEXPR_NUM_THREADS')},
        'wall_seconds': None,
    }
    identity = {
        'case_dir': str(case_dir), 'parent_dir': str(parent_dir),
        'input_file_hashes_pre': pre_hashes,
        'input_file_hashes_post': post_hashes,
        'parent_summary_sha256_pre': summary_hash_pre,
        'parent_summary_sha256_post': summary_hash_post,
        'inputs_unchanged': post_hashes == pre_hashes
                             and summary_hash_post == summary_hash_pre,
        'manifest_verified': True,
    }
    controls = {
        'expected_case_hash': str(args.expected_case_hash),
        'retained_dofs': [int(d) for d in args.retained_dofs],
        'angular_counts': [int(c) for c in args.angular_counts],
        'rlimit_mib': int(args.rlimit_mib),
        'registered_frozen_rate': [float(v) for v in REGISTERED_FROZEN_RATE],
        'note': 'effective values actually used by this run; the CLI accepts '
                'only the registered actual controls',
    }
    report = build_report(case, frozen, identity, runtime, {'A': A, 'b': b,
                                                            'operator_files': operator_files},
                          solve_meta, fields, retained, angular_counts, controls)
    report['runtime']['wall_seconds'] = time.perf_counter() - started

    np.savez_compressed(output_dir / 'candidate-solve.npz',
                        A=A, b=b, sigma=sigma, phi=fields['phi'],
                        pressure=fields['pressure'],
                        node_residual=fields['node_residual'],
                        mean_residual=fields['mean_residual'],
                        force_per_velocity=fields['force'],
                        added_mass=fields['force'].imag / frozen['omega'],
                        radiation_damping=-fields['force'].real,
                        rate=frozen['rate'],
                        dofs=np.asarray(case['dofs']))
    (output_dir / 'candidate-solve.json').write_text(
        json.dumps(report, indent=2), encoding='utf-8')
    write_markdown(output_dir / 'candidate-solve.md', report)
    write_status(output_dir, 'completed_unqualified', solve_attempts_this_run=1,
                 source_admission=False, qualification=False,
                 wall_seconds=report['runtime']['wall_seconds'])
    return report


def _failure_status(ownership: dict, state: str, **extra) -> None:
    """Write a failure record only to the fresh output directory actually
    created and owned by THIS run.

    A caller-supplied pre-existing, refused or symlinked destination is
    never written: ownership is the directory this run itself created,
    never revalidated by a mere exists() check.
    """
    owned = ownership.get('owned_output')
    if owned is not None:
        write_status(owned, state, **extra)


def main(argv=None) -> int:
    args = parse_args(argv)
    ownership = {}
    try:
        validate_actual_controls(args)
        run(args, ownership)
    except CandidateRefusal as exc:
        print(f'refused: {exc}', file=sys.stderr)
        _failure_status(ownership, 'refused', reason=str(exc))
        return 1
    except CandidateSolveError as exc:
        print(f'solve failed: {exc}', file=sys.stderr)
        _failure_status(ownership, 'solve_failed', reason=str(exc),
                        solve_attempts_this_run=1)
        return 2
    except Exception as exc:
        print(f'internal failure: {exc}', file=sys.stderr)
        traceback.print_exc()
        _failure_status(ownership, 'failed', reason=f'{type(exc).__name__}: {exc}',
                        traceback=traceback.format_exc())
        return 3
    return 0


if __name__ == '__main__':
    sys.exit(main())
