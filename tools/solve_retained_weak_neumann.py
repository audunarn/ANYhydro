"""Retained-field physical-hull potential-tested Neumann candidate solver.

Experimental Petrov-Galerkin candidate for one frozen development radiation
case. It keeps the continuum geometry, outgoing field kernel, phasor
exp(-i omega t), artificial internal lid constraints and the full coupled
DOF inventory of the stored case, and replaces only the physical-hull test
space: instead of the original panel-mean collocation rows on the hull, the
hull equations project the stored boundary relation onto potentials
generated by the hull source columns themselves.

For hull panel indices H (artificial lid L, hull source columns J = H),
stored per-receiver-node operators S_q (source density -> node potential)
and K_q (source density -> node normal velocity, already containing the
+0.5 self jump; never added again), quadrature weights w and rigid trace g
(zero on the lid), the assembled system is exactly

    A[H, :] = sum_q S_q[H, J]^H diag(w[H, q]) K_q[H, :]
    b[H, :] = sum_q S_q[H, J]^H diag(w[H, q]) g[H, q, :]
    A[L, :] = sum_q diag(w[L, q] / area[L]) K_q[L, :]   (original rows)
    b[L, :] = sum_q diag(w[L, q] / area[L]) g[L, q, :]  (zero on the lid)

solved as A sigma = b for all source columns and the full right-hand-side
DOF block. Node potential, pressure p = i rho omega S sigma, normal
velocity residual K sigma - g, panel-mean residual and the physical hull
force F[d, e] = -sum_hq w conj(g_d) p_e are recovered through the exact
stored operators; A_added = Im(F)/omega, B = -Re(F).

Diagnostics compare the candidate against the original stored fields:
unclipped symmetric damping eigenvalues, weak and panel-mean residuals
(distinct units and normalization), pressure-residual work, physical-hull
flux, near mechanical work and the unchanged source-pole/angular radiated
power formulas at the frozen rate and retained coordinates. The closure
verdict uses the original gate normalization (relative 0.03, absolute
1e-8, near-zero floor 1e-8, scale = max(|candidate|, |reference|)) with no
tolerance change.

Honest limits: this is one experimental development case at one frequency;
a potential-weighted test space does not guarantee conservation,
reciprocity, positivity or lower error, and no such property is claimed or
enforced. The selected hull-source test space does not contain every
lid-generated physical-hull potential, so the full pressure-residual work
is reported. No auxiliary lid flux is physical outward fluid flux. The
source-pole far construction is the existing frozen formula, not
independent physical evidence. No Green function, native, Capytaine, HAMS
or Prony evaluation is performed and no BEM kernel assembly occurs; only
the stored operators are used. A passing single case cannot establish W5
or any capability: general admission is false and W5 NO_GO is unchanged
regardless of the outcome. Inputs are never modified; outputs go only to
a fresh directory outside the immutable case and parent trees, and
failure records are written only to that fresh directory after this run
itself created and owns it — never to a caller-supplied pre-existing or
refused destination.
"""
