class CandidateRefusal(RuntimeError):
    """Raised when the candidate refuses to proceed (identity/safety)."""


class CandidateSolveError(RuntimeError):
    """Raised when the assembled linear system cannot be solved."""


def _max_abs(values: np.ndarray) -> float:
    return float(np.max(np.abs(values))) if np.size(values) else 0.0


def _rel(diff: float, scale: float) -> float:
    return float(diff / max(scale, 1e-300))


def _require_finite(name: str, values: np.ndarray) -> None:
    if not np.all(np.isfinite(values)):
        raise CandidateRefusal(f'nonfinite values in stored {name}')


def load_json_file(path: Path, label: str) -> dict:
    if not path.is_file():
        raise CandidateRefusal(f'missing required {label}: {path}')
    try:
        return json.loads(path.read_text(encoding='utf-8'))
    except Exception as exc:
        raise CandidateRefusal(f'unreadable {label} at {path}: {exc}') from exc


def load_npz_arrays(path: Path, label: str) -> dict:
    if not path.is_file():
        raise CandidateRefusal(f'missing required {label}: {path}')
    try:
        with np.load(path, allow_pickle=False) as data:
            return {name: np.asarray(data[name]) for name in data.files}
    except Exception as exc:
        raise CandidateRefusal(f'refusing to load {label} from {path}: {exc}') from exc


def verify_manifest(arrays: dict, case_json: dict) -> None:
    """snapshot_arrays manifest identity: exact key/shape/dtype/content match."""
    manifest = case_json.get('snapshot_arrays')
    if not isinstance(manifest, dict) or not manifest:
        raise CandidateRefusal('case.json snapshot_arrays manifest missing or empty')
    if set(manifest.keys()) != set(arrays.keys()):
        raise CandidateRefusal(
            f'snapshot_arrays manifest keys {sorted(manifest)} do not match '
            f'input arrays {sorted(arrays)}')
    for name in sorted(manifest):
        spec = manifest[name]
        if not isinstance(spec, dict) or not all(k in spec for k in ('shape', 'dtype', 'sha256')):
            raise CandidateRefusal(f'manifest entry for {name!r} is incomplete')
        arr = arrays[name]
        if list(spec['shape']) != list(arr.shape):
            raise CandidateRefusal(f'manifest shape mismatch for {name}: '
                                   f'{spec["shape"]} != {list(arr.shape)}')
        if str(spec['dtype']) != arr.dtype.name:
            raise CandidateRefusal(f'manifest dtype mismatch for {name}: '
                                   f'{spec["dtype"]} != {arr.dtype.name}')
        if sha256_array(arr) != str(spec['sha256']):
            raise CandidateRefusal(f'manifest sha256 mismatch for input array {name}: '
                                   'arrays do not match the case snapshot')


def load_candidate_case(case_dir: Path, expected_case_hash: str) -> dict:
    """Verified fixed-case manifest/hash/shape/dtype/finite/geometry loading."""
    case_json = load_json_file(case_dir / 'case.json', 'case.json')
    load_json_file(case_dir / 'status.json', 'status.json')
    case_hash = case_json.get('case_hash')
    if case_hash != expected_case_hash:
        raise CandidateRefusal(f'case_hash mismatch: {case_hash!r} != '
                               f'{expected_case_hash!r}')
    arrays = load_npz_arrays(case_dir / 'input.npz', 'input.npz')
    verify_manifest(arrays, case_json)
    for name in REQUIRED_INPUT_ARRAYS:
        if name not in arrays:
            raise CandidateRefusal(f'input.npz is missing required array: {name}')
    validate_arrays(arrays, case_json)
    radiation = load_npz_arrays(case_dir / 'radiation.npz', 'radiation.npz')
    for name in REQUIRED_RADIATION_ARRAYS:
        if name not in radiation:
            raise CandidateRefusal(f'radiation.npz is missing required array: {name}')
    points = arrays['points']
    weights = arrays['weights']
    hull = np.asarray(arrays['hull_mask'], dtype=bool)
    trace = arrays['rigid_trace']
    count, nq, _ = points.shape
    dofs = [str(d) for d in np.asarray(radiation['dofs']).tolist()]
    ndof = len(dofs)
    if np.asarray(radiation['dofs']).ndim != 1 or len(set(dofs)) != ndof or ndof < 1:
        raise CandidateRefusal('stored DOFs must be a unique one-dimensional list')
    expected = {'sources': (count, ndof), 'pressure': (count, nq, ndof),
                'node_residual': (count, nq, ndof), 'mean_residual': (count, ndof),
                'force_per_velocity': (ndof, ndof), 'added_mass': (ndof, ndof),
                'radiation_damping': (ndof, ndof)}
    for name, shape in expected.items():
        if radiation[name].shape != shape:
            raise CandidateRefusal(f'radiation array {name} shape {radiation[name].shape} '
                                   f'inconsistent with {shape}')
    if trace.shape != (count, nq, ndof):
        raise CandidateRefusal(f'rigid_trace shape {trace.shape} inconsistent with '
                               f'{(count, nq, ndof)}')
    if np.any(weights <= 0):
        raise CandidateRefusal('stored quadrature weights must be positive')
    for name, values in list(arrays.items()) + list(radiation.items()):
        if values.dtype.kind in 'fc':
            _require_finite(name, values)
    if np.any(trace[~hull] != 0):
        raise CandidateRefusal('stored rigid trace must be zero on artificial lid panels')
    if not np.any(hull) or np.all(hull):
        raise CandidateRefusal('case must contain both physical hull and artificial lid panels')
    return {
        'case_json': case_json, 'points': points, 'weights': weights,
        'normals': arrays['normals'], 'hull': hull, 'trace': trace,
        'areas': weights.sum(axis=1), 'count': count, 'nq': nq, 'ndof': ndof,
        'dofs': dofs, 'radiation': radiation,
        'body_ids': [str(b) for b in case_json.get('body_ids', [])],
    }


def load_frozen_rate(parent_dir: Path, case: dict) -> dict:
    """Frozen rate and physical parameters recovered from the parent summary.

    The parent summary is an input like the case files: its rate must be
    exactly the registered frozen vector (a matching case_hash and vector
    length alone are not authority to substitute a different rate), its
    omega/rho/water_depth must agree with case.json, and its k must fit the
    declared finite-depth dispersion relation omega^2 = g k tanh(k h)
    under the original gravity and settings.
    """
    summary = load_json_file(parent_dir / 'summary.json', 'parent summary.json')
    candidate = summary.get('candidate', {})
    if candidate.get('case_hash') != case['case_json'].get('case_hash'):
        raise CandidateRefusal('parent summary case_hash missing or mismatched')
    rate_list = candidate.get('rate')
    ndof = case['ndof']
    if not isinstance(rate_list, list) or len(rate_list) != ndof:
        raise CandidateRefusal(f'parent summary rate must list {ndof} entries')
    registered = [float(v) for v in REGISTERED_FROZEN_RATE]
    if [float(v) for v in rate_list] != registered:
        raise CandidateRefusal('parent summary rate does not match the '
                               'registered frozen rate vector; matching '
                               'case_hash and length are not authority to '
                               'substitute a different rate')
    rate = np.asarray(rate_list, dtype=float)
    if not np.all(np.isfinite(rate)) or not np.any(rate):
        raise CandidateRefusal('frozen rate must be finite and nonzero somewhere')
    case_json = case['case_json']
    for key in ('omega', 'rho', 'water_depth'):
        if key not in candidate:
            raise CandidateRefusal(f'parent summary candidate.{key} is required')
        if float(candidate[key]) != float(case_json.get(key, 0.0)):
            raise CandidateRefusal(f'parent summary candidate.{key}={candidate[key]!r} '
                                   f'does not agree with case.json {key}='
                                   f'{case_json.get(key)!r}')
    omega = float(candidate['omega'])
    rho = float(candidate['rho'])
    water_depth = float(candidate['water_depth'])
    if 'k' not in candidate:
        raise CandidateRefusal('parent summary candidate.k is required')
    k = float(candidate['k'])
    gravity = float(case_json.get('gravity', 9.81))
    if not all(math.isfinite(v) for v in (omega, rho, water_depth, k, gravity)) \
            or omega <= 0 or rho <= 0 or water_depth <= 0 or k <= 0 or gravity <= 0:
        raise CandidateRefusal('omega, rho, water_depth, k and gravity must be positive')
    dispersion_residual = omega ** 2 - gravity * k * math.tanh(k * water_depth)
    dispersion_relative = abs(dispersion_residual) / omega ** 2
    if dispersion_relative > DISPERSION_RELATIVE_TOLERANCE:
        raise CandidateRefusal(f'declared k={k!r} does not fit the finite-depth '
                               f'dispersion relation omega^2 = g k tanh(k h) '
                               f'under gravity {gravity!r} and depth '
                               f'{water_depth!r} (relative residual '
                               f'{dispersion_relative:.3e})')
    return {'rate': rate, 'omega': omega, 'rho': rho, 'water_depth': water_depth,
            'k': k, 'gravity': gravity,
            'dispersion_relative_residual': dispersion_relative}


def authenticate_operator(case_dir: Path, qi: int, count: int) -> tuple[np.ndarray, np.ndarray]:
    """Load and authenticate one stored operator pair (shapes/dtype/finite)."""
    arrays = load_npz_arrays(case_dir / f'operator-{qi}.npz', f'operator-{qi}.npz')
    if not set(arrays.keys()) == {'s', 'k'}:
        raise CandidateRefusal(f'operator-{qi}.npz must contain exactly s and k, '
                               f'found {sorted(arrays)}')
    s, kmat = arrays['s'], arrays['k']
    for name, values in (('s', s), ('k', kmat)):
        if values.shape != (count, count):
            raise CandidateRefusal(f'operator-{qi}.npz {name} shape {values.shape} '
                                   f'inconsistent with {count} panels')
        if values.dtype != np.complex128:
            raise CandidateRefusal(f'operator-{qi}.npz {name} dtype {values.dtype} '
                                   'is not complex128')
        _require_finite(f'operator-{qi} {name}', values)
    return s, kmat


def accumulate_quadrature(A: np.ndarray, b: np.ndarray, S: np.ndarray, K: np.ndarray,
                          w_q: np.ndarray, trace_q: np.ndarray, H: np.ndarray,
                          L: np.ndarray, areas: np.ndarray) -> None:
    """Accumulate one receiver node's hull weak rows and original lid rows.

    Hull rows use the conjugated hull-source potential test space
    S[H, J]^H diag(w[H, q]) with J = H; lid rows keep the original panel
    means diag(w[L, q]/area[L]). The stored K already contains its +0.5
    jump and is used exactly as stored; no jump is added here.
    """
    T = S[np.ix_(H, H)]
    T_h = T.conj().T
    A[H] += T_h @ (w_q[H, None] * K[H, :])
    b[H] += T_h @ (w_q[H, None] * trace_q[H, :])
    A[L] += (w_q[L] / areas[L])[:, None] * K[L, :]
    b[L] += (w_q[L] / areas[L])[:, None] * trace_q[L, :]


def assemble_candidate_system(case_dir: Path, case: dict) -> tuple[np.ndarray, np.ndarray]:
    """Sequential assembly over receiver nodes; no operator stacks are kept."""
    count, nq, ndof = case['count'], case['nq'], case['ndof']
    H = np.flatnonzero(case['hull'])
    L = np.flatnonzero(~case['hull'])
    A = np.zeros((count, count), dtype=complex)
    b = np.zeros((count, ndof), dtype=complex)
    for qi in range(nq):
        S, K = authenticate_operator(case_dir, qi, count)
        accumulate_quadrature(A, b, S, K, case['weights'][:, qi],
                              case['trace'][:, qi, :], H, L, case['areas'])
        del S, K
    if not np.all(np.isfinite(A)) or not np.all(np.isfinite(b)):
        raise CandidateRefusal('assembled candidate system contains nonfinite entries')
    return A, b


def solve_equilibrated(A: np.ndarray, b: np.ndarray) -> tuple[np.ndarray, dict]:
    """Row-equilibrated solve of A sigma = b; equation semantics preserved.

    Row scaling is a preconditioner only: the returned sigma solves the
    original unscaled rows, verified by an explicit residual.
    """
    scale = np.max(np.abs(A), axis=1)
    if not np.all(np.isfinite(scale)) or np.any(scale <= 0):
        raise CandidateSolveError('assembled system has zero or nonfinite row scale '
                                  '(singular or degenerate rows)')
    rows = 1.0 / scale
    try:
        sigma = np.linalg.solve(A * rows[:, None], b * rows[:, None])
    except np.linalg.LinAlgError as exc:
        raise CandidateSolveError(f'linear solve failed: {exc}') from exc
    if not np.all(np.isfinite(sigma)):
        raise CandidateSolveError('linear solve produced nonfinite source densities')
    residual = A @ sigma - b
    per_column = [float(np.linalg.norm(residual[:, d]) / max(np.linalg.norm(b[:, d]), 1e-300))
                  for d in range(b.shape[1])]
    meta = {
        'row_equilibration': 'per-row 1/max|A[i,:]| preconditioning; unscaled '
                             'equations verified by explicit residual',
        'row_scale_min': float(np.min(scale)),
        'row_scale_max': float(np.max(scale)),
        'equation_residual_max_abs': _max_abs(residual),
        'equation_residual_rel_per_dof': per_column,
    }
    return sigma, meta


def recover_fields(case_dir: Path, case: dict, sigma: np.ndarray,
                   rho: float, omega: float) -> dict:
    """Recover node potential, pressure, residuals and force through the
    exact stored operators (second sequential pass; no operator stacks)."""
    count, nq, ndof = case['count'], case['nq'], case['ndof']
    weights, hull, trace = case['weights'], case['hull'], case['trace']
    areas = case['areas']
    phi = np.zeros((count, nq, ndof), dtype=complex)
    pressure = np.zeros((count, nq, ndof), dtype=complex)
    node_residual = np.zeros((count, nq, ndof), dtype=complex)
    mean_k = np.zeros((count, count), dtype=complex)
    far_form = np.zeros((ndof, ndof), dtype=complex)
    for qi in range(nq):
        S, K = authenticate_operator(case_dir, qi, count)
        phi[:, qi, :] = S @ sigma
        pressure[:, qi, :] = 1j * rho * omega * phi[:, qi, :]
        node_residual[:, qi, :] = K @ sigma - trace[:, qi, :]
        mean_k += (weights[:, qi] / areas)[:, None] * K
        far_form += np.einsum('i,id,ie->de', weights[:, qi], sigma.conj(),
                              S.imag @ sigma)
        del S, K
    mean_rhs = np.einsum('iq,iqd->id', weights / areas[:, None], trace)
    mean_residual = mean_k @ sigma - mean_rhs
    force = -np.einsum('iq,iqd,iqe->de', weights[hull], np.conj(trace[hull]),
                       pressure[hull])
    for name, values in (('potential', phi), ('pressure', pressure),
                         ('node_residual', node_residual),
                         ('mean_residual', mean_residual), ('force', force)):
        _require_finite(f'recovered {name}', values)
    return {'phi': phi, 'pressure': pressure, 'node_residual': node_residual,
            'mean_residual': mean_residual, 'force': force, 'far_form': far_form}


def physical_hull_force(weights: np.ndarray, hull: np.ndarray, trace: np.ndarray,
                        pressure: np.ndarray) -> np.ndarray:
    """F[d, e] = -sum_hq w conj(g_d) p_e over physical hull panels."""
    return -np.einsum('iq,iqd,iqe->de', weights[hull], np.conj(trace[hull]),
                      pressure[hull])


def closure_verdict(far_w: float, near_w: float) -> dict:
    """Original gate normalization, unchanged: rel 0.03, abs 1e-8, floor 1e-8."""
    far_w, near_w = float(far_w), float(near_w)
    if not math.isfinite(far_w) or not math.isfinite(near_w):
        raise CandidateRefusal('nonfinite closure inputs are refused, never classified')
    scale = max(abs(far_w), abs(near_w))
    if scale < CLOSURE_FLOOR:
        scale = CLOSURE_FLOOR
    limit = CLOSURE_ABSOLUTE + CLOSURE_RELATIVE * scale
    diff = abs(far_w - near_w)
    return {'far_w': far_w, 'near_w': near_w, 'diff': diff, 'scale': scale,
            'limit': limit, 'verdict': 'pass' if diff <= limit else 'fail',
            'normalization': 'original gate: relative 0.03, absolute 1e-8, '
                             'near-zero floor 1e-8, scale=max(|far|,|near|)'}


def rate_diagnostics(case: dict, fields: dict, frozen: dict, rate: np.ndarray,
                     angular_counts) -> dict:
    """Frozen-rate and per-retained-DOF energetic diagnostics for one field set."""
    weights, hull, trace = case['weights'], case['hull'], case['trace']
    pressure, node_residual = fields['pressure'], fields['node_residual']
    force, sigma = fields['force'], fields['sigma']
    pressure_v = pressure @ rate
    trace_v = trace @ rate
    residual_v = node_residual @ rate
    sigma_v = sigma @ rate
    near = near_power(force, rate)
    work = boundary_work(weights, hull, pressure_v, trace_v)
    flux = actual_flux(weights, pressure_v, trace_v, residual_v)
    hull_flux = .5 * float(np.real(np.sum(weights[hull] * pressure_v[hull]
                                          * np.conj(trace_v[hull] + residual_v[hull]))))
    residual_diag = residual_diagnostics(weights, hull, pressure_v, residual_v)
    far = far_mean_powers(case['points'], weights, sigma_v, k=frozen['k'],
                          rho=frozen['rho'], omega=frozen['omega'],
                          water_depth=frozen['water_depth'],
                          angular_counts=angular_counts)
    largest = max(angular_counts)
    return {
        'near_w': near, 'boundary_work_w': work, 'force_work_error_w': abs(near - work),
        'actual_flux_w': flux, 'physical_hull_flux_w': hull_flux,
        'lid_flux_note': 'artificial lid flux is not physical outward fluid flux',
        'far_w': {str(c): far[c] for c in angular_counts},
        'closure_far_minus_near_w': far[largest] - near,
        'closure_verdict': closure_verdict(far[largest], near),
        'mean_residual_max_velocity_m_per_s': float(np.max(np.abs(fields['mean_residual'] @ rate))),
        'node_residual_max_velocity_m_per_s': residual_diag['node_residual_max_velocity_m_per_s'],
        **{f'residual_{key}': value for key, value in residual_diag.items()},
    }


def per_dof_diagnostics(case: dict, fields: dict, frozen: dict, retained,
                        angular_counts) -> list:
    largest = max(angular_counts)
    weights, hull = case['weights'], case['hull']
    entries = []
    for d in retained:
        unit = np.zeros(case['ndof'])
        unit[d] = 1.0
        p_d = fields['pressure'] @ unit
        g_d = case['trace'] @ unit
        r_d = fields['node_residual'] @ unit
        near_d = near_power(fields['force'], unit)
        work_d = boundary_work(weights, hull, p_d, g_d)
        far_d = far_mean_powers(case['points'], weights, fields['sigma'][:, d],
                                k=frozen['k'], rho=frozen['rho'],
                                omega=frozen['omega'],
                                water_depth=frozen['water_depth'],
                                angular_counts=(largest,))
        diag = residual_diagnostics(weights, hull, p_d, r_d)
        entries.append({
            'dof_index': int(d), 'dof': case['dofs'][d],
            'near_w': near_d, 'boundary_work_w': work_d,
            'far_w': {str(largest): far_d[largest]},
            'closure_far_minus_near_w': far_d[largest] - near_d,
            'closure_verdict': closure_verdict(far_d[largest], near_d),
            'residual_work_all_w': diag['residual_work_all_w'],
            'residual_work_hull_w': diag['residual_work_hull_w'],
            'node_residual_max_velocity_m_per_s': diag['node_residual_max_velocity_m_per_s'],
        })
    return entries


def build_report(case: dict, frozen: dict, identity: dict, runtime: dict,
                 assembly: dict, solve_meta: dict, fields: dict, retained,
                 angular_counts, controls: dict) -> dict:
    ndof = case['ndof']
    rate = frozen['rate']
    force = fields['force']
    added_mass = force.imag / frozen['omega']
    damping = -force.real
    retained_idx = list(retained)
    B_ret = damping[np.ix_(retained_idx, retained_idx)]
    sym_full = .5 * (damping + damping.T)
    sym_ret = .5 * (B_ret + B_ret.T)
    weak_residual = assembly['A'] @ fields['sigma'] - assembly['b']
    H = np.flatnonzero(case['hull'])
    L = np.flatnonzero(~case['hull'])
    lid_row_identity = _max_abs(weak_residual[L] - fields['mean_residual'][L])

    candidate_diag = rate_diagnostics(case, fields, frozen, rate, angular_counts)
    candidate_per_dof = per_dof_diagnostics(case, fields, frozen, retained, angular_counts)

    original = case['radiation']
    orig_fields = {'pressure': original['pressure'],
                   'node_residual': original['node_residual'],
                   'mean_residual': original['mean_residual'],
                   'force': original['force_per_velocity'], 'sigma': original['sources']}
    original_diag = rate_diagnostics(case, orig_fields, frozen, rate, angular_counts)
    original_per_dof = per_dof_diagnostics(case, orig_fields, frozen, retained,
                                           angular_counts)

    comparison = {
        'note': 'original values recomputed from the stored retained fields of the '
                'same case; the frozen rate is recovered from the parent summary, '
                'not chosen',
        'sigma_max_abs_diff': _max_abs(fields['sigma'] - original['sources']),
        'sigma_rel_diff': _rel(_max_abs(fields['sigma'] - original['sources']),
                               _max_abs(original['sources'])),
        'force_max_abs_diff': _max_abs(force - original['force_per_velocity']),
        'force_rel_diff': _rel(_max_abs(force - original['force_per_velocity']),
                               _max_abs(original['force_per_velocity'])),
        'original': original_diag,
        'original_per_dof': original_per_dof,
        'closure_verdict_change': {
            'original': original_diag['closure_verdict']['verdict'],
            'candidate': candidate_diag['closure_verdict']['verdict'],
        },
    }

    return {
        'format': FORMAT,
        'status': 'completed_unqualified',
        'source_admission': False,
        'qualification': False,
        'generated_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'tool': {'path': str(Path(__file__)), 'sha256': sha256_file(Path(__file__)),
                 'numpy_version': np.__version__, 'python': platform.python_version(),
                 'platform': platform.platform()},
        'honest_limits': list(HONEST_LIMITS),
        'runtime': runtime,
        'identity': identity,
        'effective_controls': dict(controls),
        'case': {
            'case_hash': case['case_json'].get('case_hash'),
            'panels': case['count'], 'receiver_nodes': case['nq'],
            'hull_panels': int(len(H)), 'lid_panels': int(len(L)),
            'dofs': case['dofs'], 'body_ids': case['body_ids'],
            'omega': frozen['omega'], 'rho': frozen['rho'],
            'water_depth': frozen['water_depth'], 'k': frozen['k'],
            'gravity': frozen['gravity'],
            'dispersion_relative_residual': frozen['dispersion_relative_residual'],
            'retained_dofs': [int(d) for d in retained],
            'frozen_rate_vector': [float(v) for v in rate],
        },
        'assembly': {
            'hull_rows': 'sum_q S_q[H,J]^H diag(w[H,q]) K_q[H,:] with J=H; '
                         'conjugated potential test space (Petrov-Galerkin)',
            'lid_rows': 'original panel means sum_q diag(w[L,q]/area[L]) K_q[L,:]',
            'jump_handling': 'stored K already contains the +0.5 jump; used as stored, '
                            'never added again',
            'operator_files': assembly['operator_files'],
        },
        'solve': solve_meta,
        'weak_residual': {
            'max_abs': _max_abs(weak_residual),
            'hull_rows_max_abs': _max_abs(weak_residual[H]),
            'lid_rows_max_abs': _max_abs(weak_residual[L]),
            'rel_to_rhs': _rel(_max_abs(weak_residual), _max_abs(assembly['b'])),
            'lid_rows_equal_mean_residual_max_abs': lid_row_identity,
            'units_note': 'weak equation residual in potential-weighted test units '
                          '(mixed potential*area*velocity per source unit); distinct '
                          'from the panel-mean residual reported in m/s',
        },
        'fields': {
            'node_potential_max_abs': _max_abs(fields['phi']),
            'pressure_max_abs': _max_abs(fields['pressure']),
            'node_residual_max_velocity_m_per_s':
                float(np.max(np.abs(fields['node_residual']))),
            'mean_residual_max_velocity_m_per_s':
                float(np.max(np.abs(fields['mean_residual']))),
            'pressure_convention': 'p = i rho omega phi, phasor exp(-i omega t)',
        },
        'coefficients': {
            'convention': 'F[d,e] = -sum_hq w conj(g_d) p_e; added_mass = Im(F)/omega; '
                          'radiation_damping = -Re(F); full coupled DOF inventory '
                          'preserved, no symmetrization or clipping applied',
            'force_per_velocity': {'real': force.real.tolist(), 'imag': force.imag.tolist()},
            'added_mass': added_mass.tolist(),
            'radiation_damping': damping.tolist(),
            'damping_symmetric_eigenvalues_unclipped_full':
                [float(v) for v in np.linalg.eigvalsh(sym_full)],
            'damping_symmetric_eigenvalues_unclipped_retained':
                [float(v) for v in np.linalg.eigvalsh(sym_ret)],
            'damping_asym_rel': _rel(_max_abs(damping - damping.T), _max_abs(damping)),
        },
        'candidate_rate': candidate_diag,
        'candidate_per_dof': candidate_per_dof,
        'original_comparison': comparison,
    }


def write_status(output_dir: Path, state: str, **extra) -> None:
    """Merge-write status; solve counts recorded before the solve are never lost."""
    payload = {'format': FORMAT, 'state': state,
               'updated_utc': datetime.datetime.now(datetime.timezone.utc).isoformat()}
    status_path = output_dir / 'status.json'
    if status_path.is_file():
        try:
            previous = json.loads(status_path.read_text(encoding='utf-8'))
            for key in ('solve_attempts_this_run', 'solve_recorded_before_solve'):
                if key in previous:
                    payload[key] = previous[key]
        except Exception:
            pass
    payload.update(extra)
    status_path.write_text(json.dumps(payload, indent=2), encoding='utf-8')


